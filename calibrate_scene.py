"""C3 calibration from DEV only: fit sqrt(area) = k*y_bottom + c on single-person blobs, choose head_alpha by dev MAE,
then write [scene.perspective] into configs/scenes/<scene>.toml."""
import argparse
from dataclasses import replace
import numpy as np
from object_counting.io import ROOT, read_csv, load_params, load_scene, read_image, resolve, load_points
from object_counting.pipeline import count_image
from object_counting.counting import fit_perspective

ALPHAS = (.10, .12, .15, .18, .22)


def single_person_blobs(result, points, margin=3):
    pairs = []
    for r in result.regions:
        x, y, w, h = r['bbox']
        if sum(x-margin <= px < x+w+margin and y-margin <= py < y+h+margin for px, py in points) == 1:
            pairs.append((r['y_bottom'], r['area']))
    return pairs


def calibrate(scene_id, config='configs/baseline.toml', ratio=.3, root=ROOT):
    rows = [r for r in read_csv(root/'data/week1/manifests/dev.csv') if r['scene_id'] == scene_id]
    if not rows:
        raise ValueError(f'{scene_id} không có ảnh dev; không được fit phối cảnh từ test.')
    params, _ = load_params(config, root)
    scene, bg, roi = load_scene(scene_id, root)
    points = load_points(root); labels = {r['image_id']: int(r['count']) for r in read_csv(root/'data/week1/annotations/counts.csv')}
    images = {r['image_id']: read_image(resolve(r['image'], root)) for r in rows}
    pairs = [p for r in rows for p in single_person_blobs(count_image(images[r['image_id']], bg, params, roi), points.get(r['image_id'], []))]
    k, c = fit_perspective(pairs)
    model = dict(k=k, c=c, min_area_ratio=ratio)
    scores = {}
    for alpha in ALPHAS:
        p = dict(model, head_alpha=alpha); hough = replace(params, count_method='area_hough')
        scores[alpha] = float(np.mean([abs(count_image(images[i], bg, hough, roi, p).count-labels[i]) for i in images]))
    model['head_alpha'] = min(scores, key=scores.get)
    return dict(model, fitted_from='data/week1/manifests/dev.csv', single_person_blobs=len(pairs)), scores


def write_perspective(scene_id, model, root=ROOT):
    path = root/'configs/scenes'/f'{scene_id}.toml'
    text = path.read_text().split('\n[scene.perspective]')[0].rstrip('\n')
    block = '\n\n[scene.perspective]  # generated by calibrate_scene.py from DEV only\n'
    block += ''.join(f'{key} = {value!r}\n' if not isinstance(value, str) else f'{key} = "{value}"\n' for key, value in model.items())
    path.write_text(text+block)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scene', nargs='+', default=['scene_01', 'scene_02'])
    parser.add_argument('--config', default='configs/baseline.toml')
    args = parser.parse_args()
    for scene_id in args.scene:
        model, scores = calibrate(scene_id, args.config)
        write_perspective(scene_id, model)
        print(scene_id, model, 'dev MAE by alpha:', {a: round(s, 3) for a, s in scores.items()})


if __name__ == '__main__':
    main()
